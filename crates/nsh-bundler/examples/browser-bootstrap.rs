//! Regenerate the checked-in classic bootstrap, or verify it with `--check`.
//! Keeping this artifact in the checkout lets the browser host run directly,
//! without adding a bundler or build step to application startup.

use std::{fs, path::PathBuf};

use rolldown::{Bundler, BundlerOptions, InputItem, OutputFormat, RawMinifyOptions};
use rolldown_common::{CodeSplittingMode, Output};

fn main() -> anyhow::Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../nsh-platform-web/web/browser");
    let options = BundlerOptions {
        cwd: Some(fs::canonicalize(&root)?),
        input: Some(vec![InputItem {
            import: "./bootstrap.js".into(),
            ..Default::default()
        }]),
        format: Some(OutputFormat::Iife),
        minify: Some(RawMinifyOptions::Bool(true)),
        code_splitting: Some(CodeSplittingMode::Bool(false)),
        ..Default::default()
    };
    let mut bundler =
        Bundler::with_plugins(options, vec![]).map_err(|errors| anyhow::anyhow!("{errors:?}"))?;
    let output = tokio::runtime::Builder::new_current_thread()
        .build()?
        .block_on(bundler.generate())
        .map_err(|errors| anyhow::anyhow!("{errors:?}"))?;
    anyhow::ensure!(output.assets.len() == 1, "bootstrap must be one script");
    let Output::Chunk(chunk) = &output.assets[0] else {
        anyhow::bail!("bootstrap must be JavaScript");
    };
    anyhow::ensure!(
        chunk.imports.is_empty() && chunk.dynamic_imports.is_empty(),
        "bootstrap must not load modules before the import map"
    );
    let source = format!(
        "// Generated by cargo run -p nsh-bundler --example browser-bootstrap. Do not edit.\n\"use strict\";\n{}",
        chunk.code
    );
    let path = root.join("bootstrap.classic.js");
    if std::env::args().any(|arg| arg == "--check") {
        anyhow::ensure!(
            fs::read_to_string(path)? == source,
            "regenerate browser bootstrap"
        );
    } else {
        fs::write(path, source)?;
    }
    Ok(())
}
